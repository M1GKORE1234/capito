import { addEvent, emptyLedger, hasAnswered, parseLedger, serializeLedger, type Ledger, type LedgerEvent } from '../core/ledger.js';
import { GitHubError, type Api } from './api.js';

const LEDGER = 'ledger.json';

const BRANCH_README = `# Capito data

This branch is written by [Capito](https://github.com/M1GKORE1234/capito). It has no shared history with your code.

- \`ledger.json\` — every answered quiz: who answered, which files and lines it was about, right or wrong.
- \`CAPITO.md\` — the comprehension map, regenerated by the weekly run.
- \`map.json\` — the same map as data, for your own dashboards.

Delete the branch to reset everything. Set \`anonymous: true\` in the workflow to store pseudonyms instead of usernames.
`;

/** Reads and writes Capito's data on a dedicated branch of the same repository. */
export class DataStore {
  constructor(
    private api: Api,
    public branch: string,
  ) {}

  async ensureBranch(): Promise<void> {
    if (await this.api.branchExists(this.branch)) return;
    try {
      await this.api.createOrphanBranch(this.branch, { 'README.md': BRANCH_README, [LEDGER]: serializeLedger(emptyLedger()) }, 'Capito: initialise data branch');
    } catch (e) {
      // Another run may have created it in the meantime
      if (!(e instanceof GitHubError && e.status === 422)) throw e;
    }
  }

  async readLedger(): Promise<{ ledger: Ledger; sha?: string }> {
    if (!(await this.api.branchExists(this.branch))) return { ledger: emptyLedger() };
    const file = await this.api.getFile(LEDGER, this.branch);
    return { ledger: parseLedger(file?.content), sha: file?.sha };
  }

  /** Append one answer. Retries on concurrent writes; never records the same person twice for a quiz. */
  async appendEvent(event: LedgerEvent): Promise<'saved' | 'duplicate'> {
    await this.ensureBranch();
    for (let attempt = 0; attempt < 6; attempt++) {
      const { ledger, sha } = await this.readLedger();
      if (hasAnswered(ledger, event.quizId, event.user)) return 'duplicate';
      try {
        await this.api.putFile(LEDGER, this.branch, serializeLedger(addEvent(ledger, event)), `Capito: ${event.user} answered quiz ${event.quizId} (${event.correct}/${event.total})`, sha);
        return 'saved';
      } catch (e) {
        if (e instanceof GitHubError && (e.status === 409 || e.status === 422) && attempt < 5) {
          await new Promise((r) => setTimeout(r, 300 + Math.random() * 700 * (attempt + 1)));
          continue;
        }
        throw e;
      }
    }
    throw new Error('Could not save the answer after several attempts');
  }

  async writeFiles(files: Record<string, string>, message: string): Promise<void> {
    await this.ensureBranch();
    for (const [path, content] of Object.entries(files)) {
      for (let attempt = 0; attempt < 4; attempt++) {
        const existing = await this.api.getFile(path, this.branch);
        if (existing && existing.content === content) break;
        try {
          await this.api.putFile(path, this.branch, content, message, existing?.sha);
          break;
        } catch (e) {
          if (e instanceof GitHubError && (e.status === 409 || e.status === 422) && attempt < 3) continue;
          throw e;
        }
      }
    }
  }
}
